const assert = require("node:assert/strict");
const crypto = require("node:crypto");
const fs = require("node:fs");
const path = require("node:path");
const { spawnSync } = require("node:child_process");
const { Pool } = require("pg");
const bcrypt = require("bcryptjs");
const { chromium, expect } = require("playwright/test");
const { root, readConfig } = require("./public-test-config.cjs");
const base = "https://testes.laudaapp.com";
const artifacts = path.join(root, "test-results/visual-chord-editor");
const fingerprint = 'SELECT md5(string_agg(row_to_json(s)::text, \'\' ORDER BY id)) FROM "Song" s';
function productionFingerprint() {
  const result = spawnSync("docker", ["exec", "lauda20-postgres-1", "psql", "-U", "postgres", "-d", "lauda2", "-Atc", fingerprint], { encoding: "utf8", windowsHide: true });
  assert.equal(result.status, 0, result.stderr);
  return result.stdout.trim();
}
async function main() {
  fs.mkdirSync(artifacts, { recursive: true });
  const pool = new Pool({ connectionString: readConfig().DATABASE_URL });
  const ids = { tenant: crypto.randomUUID(), user: crypto.randomUUID(), member: crypto.randomUUID(), artist: crypto.randomUUID(), song: crypto.randomUUID(), legacy: crypto.randomUUID(), blank: crypto.randomUUID() };
  const password = crypto.randomBytes(24).toString("hex");
  const email = `visual-${ids.user}@example.invalid`;
  const source = "{title: Canção de teste}\n{comment: Refrão}\n[C]Vou te cantar\nCom todo o meu coração\n\n[G] [Am]";
  const legacy = "Intro\nC  G/B (2x)\n\nC      G\nVou te cantar\n";
  const convertedLegacy = "Intro\n[C]  [G/B] (2x)\n\n[C]Vou te [G]cantar\n";
  const productionBefore = productionFingerprint();
  const testBefore = (await pool.query(fingerprint)).rows[0].md5;
  const checks = [];
  let browser;
  let page;
  const pageErrors = [];
  const badRequests = [];
  const savedPayloads = [];
  const dbContent = async id => (await pool.query('SELECT content FROM "Song" WHERE id=$1', [id])).rows[0]?.content;
  async function openEdit(target, id) {
    await target.goto(`${base}/songs/${id}/edit`, { waitUntil: "networkidle" });
    await target.getByTestId("visual-chord-editor").waitFor();
  }
  async function sourceIs(target, expected) {
    await target.getByRole("tab", { name: "Texto ChordPro", exact: true }).click();
    await expect(target.getByTestId("song-chord-input")).toHaveValue(expected);
    await target.getByRole("tab", { name: "Visual", exact: true }).click();
  }
  async function save(target, id) {
    await Promise.all([
      target.waitForResponse(response => response.url().endsWith(`/api/songs/${id}`) && response.request().method() === "PATCH" && response.status() === 200),
      target.getByTestId("song-save-button").click(),
    ]);
    await target.waitForURL(current => current.pathname === `/songs/${id}`);
  }
  function observe(target) {
    target.on("pageerror", error => pageErrors.push(error.message));
    target.on("dialog", dialog => dialog.accept());
    target.on("request", request => {
      if (new URL(request.url()).hostname === "api.laudaapp.com") badRequests.push(request.url());
      if (request.method() === "PATCH" && request.url().endsWith(`/api/songs/${ids.song}`)) savedPayloads.push(request.postDataJSON());
    });
  }
  try {
    await pool.query('INSERT INTO "Tenant" (id,name,"updatedAt") VALUES ($1,\'Laboratório de cifras\',now())', [ids.tenant]);
    const hashed = await bcrypt.hash(password, 10);
    for (const [id, role, userEmail] of [[ids.user, "TENANT_ADMIN", email], [ids.member, "MEMBER", `member-${ids.member}@example.invalid`]]) {
      await pool.query('INSERT INTO "User" (id,email,password,name,role,"tenantId","updatedAt") VALUES ($1,$2,$3,\'Pessoa de teste\',$4,$5,now())', [id, userEmail, hashed, role, ids.tenant]);
    }
    await pool.query('INSERT INTO "Artist" (id,name,"normalizedName","tenantId","updatedAt") VALUES ($1,\'Artista de exemplo\',\'artista de exemplo\',$2,now())', [ids.artist, ids.tenant]);
    for (const [id, title, content] of [[ids.song, "Canção de teste", source], [ids.legacy, "Cifra tradicional", legacy], [ids.blank, "Letra pura", ""]]) {
      await pool.query('INSERT INTO "Song" (id,title,"normalizedTitle","originalKey",content,"artistId","tenantId","createdById","updatedAt") VALUES ($1,$2,$3,\'C\',$4,$5,$6,$7,now())', [id, title, title.toLowerCase(), content, ids.artist, ids.tenant, ids.user]);
    }
    browser = await chromium.launch({ headless: true });
    page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
    observe(page);
    await page.goto(base, { waitUntil: "networkidle" });
    await page.getByTestId("login-email").fill(email);
    await page.getByTestId("login-password").fill(password);
    await page.getByTestId("login-submit").click();
    await page.waitForURL(current => !current.pathname.includes("login"));
    await openEdit(page, ids.song);
    assert.equal(await dbContent(ids.song), source);
    checks.push("Opening an existing sheet does not rewrite or save its content");
    await page.getByTestId("visual-remove-line-4").click();
    await expect(page.getByRole("dialog")).toHaveCount(0);
    await sourceIs(page, source.replace("\n\n", "\n"));
    await page.getByRole("button", { name: "Desfazer alteração da cifra", exact: true }).click();
    await sourceIs(page, source);
    await page.getByTestId("visual-remove-line-2").click();
    await expect(page.getByRole("dialog", { name: "Remover linha 3?", exact: true })).toBeVisible();
    await page.getByRole("button", { name: "Cancelar", exact: true }).click();
    await sourceIs(page, source);
    await page.getByTestId("visual-remove-line-2").click();
    await page.getByRole("button", { name: "Remover linha", exact: true }).click();
    const withoutVerse = source.split("\n").filter((_, index) => index !== 2).join("\n");
    await sourceIs(page, withoutVerse);
    assert.equal(await dbContent(ids.song), source);
    await page.getByRole("button", { name: "Desfazer alteração da cifra", exact: true }).click();
    await sourceIs(page, source);
    await page.getByRole("button", { name: "Refazer alteração da cifra", exact: true }).click();
    await sourceIs(page, withoutVerse);
    await page.getByRole("button", { name: "Desfazer alteração da cifra", exact: true }).click();
    await sourceIs(page, source);
    checks.push("Whole-line removal: blank lines, confirmation/cancel, lyric and chords removed together, undo/redo without autosave");
    await page.getByRole("button", { name: "Selecionar acorde G", exact: true }).click();
    await page.getByTestId("visual-letter-2-10").click();
    let expected = source.replace("cantar", "can[G]tar");
    await sourceIs(page, expected);
    assert.equal(await dbContent(ids.song), source, "Editor changes must not autosave");
    await page.getByTestId("visual-chord-2-1").dragTo(page.getByTestId("visual-letter-3-0"));
    await sourceIs(page, source.replace("Com todo", "[G]Com todo"));
    await page.getByRole("button", { name: "Desfazer alteração da cifra", exact: true }).click();
    await sourceIs(page, expected);
    await page.getByTestId("visual-chord-2-1").click();
    await page.getByRole("textbox", { name: "Substituir acorde", exact: true }).fill("G/B");
    await page.getByRole("button", { name: "Trocar", exact: true }).click();
    expected = expected.replace("[G]tar", "[G/B]tar");
    await page.getByTestId("visual-chord-2-1").click();
    await page.getByRole("button", { name: "Mover", exact: true }).click();
    await page.getByTestId("visual-letter-3-0").click();
    expected = expected.replace("[G/B]tar", "tar").replace("Com todo", "[G/B]Com todo");
    await sourceIs(page, expected);
    await page.getByRole("button", { name: "Desfazer alteração da cifra", exact: true }).click();
    await sourceIs(page, expected.replace("[G/B]Com", "Com").replace("cantar", "can[G/B]tar"));
    await page.getByRole("button", { name: "Refazer alteração da cifra", exact: true }).click();
    await sourceIs(page, expected);
    await page.getByTestId("visual-chord-3-0").click();
    await page.getByRole("button", { name: "Remover", exact: true }).click();
    await sourceIs(page, expected.replace("[G/B]Com", "Com"));
    await page.getByRole("button", { name: "Desfazer alteração da cifra", exact: true }).click();
    await sourceIs(page, expected);
    checks.push("Desktop: insert on a syllable, change slash chord, move across lines, remove, undo and redo");
    await page.getByRole("button", { name: "Adicionar acorde", exact: true }).click();
    await page.getByRole("textbox", { name: "Novo acorde", exact: true }).fill("Am7");
    await page.getByRole("button", { name: "Adicionar", exact: true }).click();
    await page.getByTestId("visual-letter-2-4").click();
    expected = expected.replace("Vou te", "Vou [Am7]te");
    await page.getByRole("button", { name: "Editar letra da linha 3", exact: true }).click();
    await page.getByRole("textbox", { name: "Letra da linha", exact: true }).fill("Hoje Vou te cantar");
    await page.getByRole("button", { name: "Aplicar letra", exact: true }).click();
    expected = expected.replace("[C]Vou", "Hoje [C]Vou");
    await sourceIs(page, expected);
    await page.getByRole("button", { name: "Editar letra da linha 3", exact: true }).click();
    await page.getByRole("textbox", { name: "Letra da linha", exact: true }).fill("Hoje Vou cantar");
    await expect(page.getByRole("alert")).toContainText("Am7");
    await expect(page.getByRole("button", { name: "Aplicar e remover 1 acorde(s)", exact: true })).toBeVisible();
    await page.getByRole("button", { name: "Cancelar", exact: true }).click();
    await sourceIs(page, expected);
    checks.push("Editing lyrics shifts anchors; deleting their text requires explicit removal confirmation");
    await page.getByRole("tab", { name: "Prévia", exact: true }).click();
    await expect(page.getByLabel("Cifra da música")).toContainText("Am7");
    await page.getByRole("tab", { name: "Visual", exact: true }).click();
    await page.getByTestId("visual-chord-editor").screenshot({ path: path.join(artifacts, "desktop-editor.png") });
    await page.getByTestId("visual-remove-line-4").click();
    expected = expected.replace("\n\n", "\n");
    await sourceIs(page, expected);
    await save(page, ids.song);
    assert.equal(savedPayloads.length, 1, "Only explicit Save should write through the API");
    assert.equal(savedPayloads[0].content, expected);
    assert.equal(await dbContent(ids.song), expected);
    await page.reload({ waitUntil: "networkidle" });
    await page.getByTestId("current-key").waitFor();
    await page.getByTestId("transpose-up").click();
    await expect(page.getByTestId("current-key")).toContainText("C#");
    const token = await page.evaluate(() => localStorage.getItem("auth_token"));
    const pdf = await fetch(`${base}/api/songs/export`, { method: "POST", headers: { authorization: `Bearer ${token}`, "content-type": "application/json" }, body: JSON.stringify({ songIds: [ids.song] }) });
    assert.equal(pdf.status, 200);
    assert.equal(Buffer.from(await pdf.arrayBuffer()).subarray(0, 5).toString(), "%PDF-");
    checks.push("Explicit save persists ChordPro; reopened sheet, transposition and PDF export still work");
    await openEdit(page, ids.song);
    await sourceIs(page, expected);
    await page.getByRole("button", { name: "Selecionar acorde G", exact: true }).click();
    await page.getByTestId("visual-letter-2-0").click();
    const draft = expected.replace("Hoje", "[G]Hoje");
    await page.getByTestId("app-back-button").click();
    await expect(page.getByText("Alterações não salvas", { exact: true })).toBeVisible();
    await page.getByRole("button", { name: "Manter rascunho e sair", exact: true }).click();
    await page.waitForURL(current => current.pathname === `/songs/${ids.song}`);
    assert.equal(await dbContent(ids.song), expected);
    await openEdit(page, ids.song);
    await expect(page.getByText("Rascunho disponível", { exact: true })).toBeVisible();
    await page.getByRole("button", { name: "Recuperar rascunho", exact: true }).click();
    await sourceIs(page, draft);
    await page.getByTestId("app-back-button").click();
    await page.getByRole("button", { name: "Sair sem salvar", exact: true }).click();
    await page.waitForURL(current => current.pathname === `/songs/${ids.song}`);
    assert.equal(await dbContent(ids.song), expected);
    checks.push("Unsaved exit offers draft; recovery restores visual edits; discard leaves the database unchanged");
    const mobileContext = await browser.newContext({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true, storageState: await page.context().storageState() });
    const mobile = await mobileContext.newPage();
    observe(mobile);
    await openEdit(mobile, ids.song);
    await mobile.getByRole("button", { name: "Adicionar acorde", exact: true }).tap();
    await mobile.getByRole("textbox", { name: "Novo acorde", exact: true }).fill("F#m7");
    await mobile.getByRole("button", { name: "Adicionar", exact: true }).tap();
    await mobile.getByTestId("visual-letter-2-0").tap();
    await sourceIs(mobile, expected.replace("Hoje", "[F#m7]Hoje"));
    await mobile.getByRole("button", { name: "Ampliar letras", exact: true }).tap();
    assert.equal(await mobile.evaluate(() => document.documentElement.scrollWidth > window.innerWidth), false, "Mobile page must not overflow horizontally");
    await mobile.screenshot({ path: path.join(artifacts, "mobile-editor.png") });
    await mobile.getByTestId("visual-chord-2-0").tap();
    await mobile.getByRole("button", { name: "Mover", exact: true }).tap();
    await mobile.getByTestId("visual-letter-3-4").tap();
    const mobileMoved = expected.replace("Com todo", "Com [F#m7]todo");
    await sourceIs(mobile, mobileMoved);
    await mobile.getByTestId("visual-remove-line-3").tap();
    await expect(mobile.getByRole("dialog", { name: "Remover linha 4?", exact: true })).toBeVisible();
    await mobile.screenshot({ path: path.join(artifacts, "mobile-line-removal.png") });
    await mobile.getByRole("button", { name: "Remover linha", exact: true }).tap();
    await sourceIs(mobile, mobileMoved.split("\n").filter((_, index) => index !== 3).join("\n"));
    await mobile.getByRole("button", { name: "Desfazer alteração da cifra", exact: true }).tap();
    await sourceIs(mobile, mobileMoved);
    assert.equal(await dbContent(ids.song), expected);
    await mobileContext.close();
    checks.push("390px touch browser: custom chords, enlarged letters, movement and whole-line removal with undo");
    await openEdit(page, ids.legacy);
    assert.equal(await dbContent(ids.legacy), legacy);
    await page.getByRole("button", { name: "Conferir conversão", exact: true }).click();
    await expect(page.getByTestId("visual-conversion-source")).toHaveText(convertedLegacy);
    await page.getByRole("button", { name: "Cancelar", exact: true }).click();
    assert.equal(await dbContent(ids.legacy), legacy);
    await page.getByRole("button", { name: "Conferir conversão", exact: true }).click();
    await page.getByRole("button", { name: "Aplicar conversão", exact: true }).click();
    await sourceIs(page, convertedLegacy);
    assert.equal(await dbContent(ids.legacy), legacy, "Applying conversion updates the form, not the database");
    await page.getByRole("button", { name: "Desfazer alteração da cifra", exact: true }).click();
    await page.getByRole("button", { name: "Conferir conversão", exact: true }).waitFor();
    await page.getByRole("button", { name: "Refazer alteração da cifra", exact: true }).click();
    await save(page, ids.legacy);
    assert.equal(await dbContent(ids.legacy), convertedLegacy);
    checks.push("Traditional sheets: preview, cancel, apply, undo/redo and explicit save preserve sections and repeats");
    await openEdit(page, ids.blank);
    await page.getByTestId("visual-initial-lyrics").fill("Vou te cantar\nCom todo o meu coração");
    await page.getByRole("button", { name: "Começar a cifrar", exact: true }).click();
    await expect(page.getByRole("button", { name: /^Selecionar acorde / })).toHaveCount(0);
    await page.getByRole("button", { name: "Adicionar acorde", exact: true }).click();
    await page.getByRole("textbox", { name: "Novo acorde", exact: true }).fill("C");
    await page.getByRole("button", { name: "Adicionar", exact: true }).click();
    await page.getByTestId("visual-letter-0-0").click();
    await sourceIs(page, "[C]Vou te cantar\nCom todo o meu coração");
    assert.equal(await dbContent(ids.blank), "");
    await save(page, ids.blank);
    assert.equal(await dbContent(ids.blank), "[C]Vou te cantar\nCom todo o meu coração");
    checks.push("Start from pure lyrics, explicitly add palette chords and save without guessed harmony");
    const memberLogin = await fetch(`${base}/api/auth/login`, { method: "POST", headers: { "content-type": "application/json" }, body: JSON.stringify({ email: `member-${ids.member}@example.invalid`, password }) });
    const memberAuth = (await memberLogin.json()).data;
    const denied = await fetch(`${base}/api/songs/${ids.song}`, { method: "PATCH", headers: { authorization: `Bearer ${memberAuth.accessToken || memberAuth.token}`, "content-type": "application/json" }, body: JSON.stringify({ content: "forbidden" }) });
    assert.equal(denied.status, 403);
    assert.equal(await dbContent(ids.song), expected);
    const otherSong = (await pool.query('SELECT id FROM "Song" WHERE "tenantId"<>$1 LIMIT 1', [ids.tenant])).rows[0];
    const crossTenant = await fetch(`${base}/api/songs/${otherSong.id}`, { headers: { authorization: `Bearer ${token}` } });
    assert([403, 404].includes(crossTenant.status));
    assert.deepEqual(pageErrors, []);
    assert.deepEqual(badRequests, []);
    assert.equal(productionFingerprint(), productionBefore);
    checks.push("Existing edit permissions and tenant boundaries preserved; no production requests or browser errors");
    const publicRelease = await fetch(`${base}/release.json`).then(result => result.json());
    assert.equal(publicRelease.feature, "visual-chord-editor");
    const localRelease = JSON.parse(fs.readFileSync(path.join(root, "mobile/web-build/public-test/release.json"), "utf8"));
    assert.deepEqual(publicRelease, localRelease);
    fs.writeFileSync(path.join(artifacts, "verification.json"), JSON.stringify({ verifiedAt: new Date().toISOString(), url: base, productionCatalogUnchanged: true, checks, release: publicRelease }, null, 2));
    console.log(JSON.stringify({ url: base, checks }, null, 2));
  } catch (error) {
    if (page) { await page.screenshot({ path: path.join(artifacts, "failure.png"), fullPage: true }).catch(() => {}); console.error("Browser URL:", page.url()); }
    throw error;
  } finally {
    await browser?.close();
    await pool.query('DELETE FROM "Song" WHERE id=ANY($1::text[])', [[ids.song, ids.legacy, ids.blank]]);
    await pool.query('DELETE FROM "Artist" WHERE id=$1', [ids.artist]);
    await pool.query('DELETE FROM "Tenant" WHERE id=$1', [ids.tenant]);
    assert.equal((await pool.query(fingerprint)).rows[0].md5, testBefore, "Validation must leave the original test catalog intact");
    await pool.end();
  }
}
main().catch(error => { console.error(error); process.exitCode = 1; });
