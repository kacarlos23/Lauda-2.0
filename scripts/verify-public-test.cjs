const assert = require("node:assert/strict");
const crypto = require("node:crypto");
const fs = require("node:fs");
const path = require("node:path");
const { spawnSync } = require("node:child_process");
const { Pool } = require("pg");
const bcrypt = require("bcryptjs");
const { chromium } = require("playwright");
const { root, readConfig } = require("./public-test-config.cjs");
const url = "https://testes.laudaapp.com";
const logs = path.join(root, "test-results/public-test");
function productionRead(sql) {
  assert(sql.startsWith("SELECT "), "Production validation is read-only");
  const result = spawnSync("docker", ["exec", "lauda20-postgres-1", "psql", "-U", "postgres", "-d", "lauda2", "-Atc", sql], { encoding: "utf8", windowsHide: true });
  assert.equal(result.status, 0, result.stderr);
  return result.stdout.trim();
}
async function main() {
  const env = readConfig();
  const pool = new Pool({ connectionString: env.DATABASE_URL });
  let browser;
  const userId = crypto.randomUUID();
  const email = `validation-${crypto.randomUUID()}@example.invalid`;
  const password = crypto.randomBytes(24).toString("hex");
  let song;
  const checks = [];
  try {
    song = (await pool.query(`SELECT s.* FROM "Song" s JOIN "Tenant" t ON t.id=s."tenantId" WHERE s."isActive" AND s."deletedAt" IS NULL AND t."isActive" AND t."deletedAt" IS NULL AND length(s.content)<95000 ORDER BY s.id LIMIT 1`)).rows[0];
    assert(song);
    assert.match(song.id, /^[0-9a-f-]{36}$/);
    const fingerprintSql = `SELECT md5(string_agg(row_to_json(s)::text, '' ORDER BY id)) FROM "Song" s`;
    const productionBefore = productionRead(fingerprintSql);
    const testCatalogBefore = (await pool.query(fingerprintSql)).rows[0].md5;
    const snapshot = JSON.parse(fs.readFileSync(path.join(logs, "snapshot.json"), "utf8"));
    assert.equal((await pool.query('SELECT count(*)::int count FROM "Song"')).rows[0].count, snapshot.counts.songs);
    checks.push(`Production snapshot contains ${snapshot.counts.songs} songs; later production changes are not synchronized`);
    await pool.query(`INSERT INTO "User" (id,email,password,name,role,"tenantId","createdAt","updatedAt") VALUES ($1,$2,$3,'Validação temporária','TENANT_ADMIN',$4,now(),now())`, [userId, email, await bcrypt.hash(password, 10), song.tenantId]);
    const login = await fetch(`${url}/api/auth/login`, { method: "POST", headers: { "content-type": "application/json" }, body: JSON.stringify({ email, password }) });
    assert.equal(login.status, 200);
    const data = (await login.json()).data;
    const token = data.accessToken || data.token;
    const auth = { authorization: `Bearer ${token}`, "content-type": "application/json" };
    const authMissing = await fetch(`${url}/api/songs`);
    assert.equal(authMissing.status, 401);
    const wrongEnvironment = await fetch("https://api.laudaapp.com/api/auth/me", { headers: auth });
    assert.equal(wrongEnvironment.status, 401, "Test session must be rejected in production");
    checks.push("Authentication required; test session rejected by production API");
    const changedContent = `${song.content}\n\nValidação de isolamento ${crypto.randomUUID()}`;
    const write = await fetch(`${url}/api/songs/${song.id}`, { method: "PATCH", headers: auth, body: JSON.stringify({ content: changedContent }) });
    assert.equal(write.status, 200, await write.text());
    const saved = await fetch(`${url}/api/songs/${song.id}`, { headers: auth });
    assert.equal((await saved.json()).data.content, changedContent);
    assert.equal(productionRead(fingerprintSql), productionBefore, "Production catalog changed during staging edit");
    checks.push("Real public API edit persisted only in test database; entire production catalog unchanged");
    await pool.query(`UPDATE "Song" SET content=$1,"updatedById"=$2,"updatedAt"=$3 WHERE id=$4`, [song.content, song.updatedById, song.updatedAt, song.id]);
    assert.equal((await pool.query(fingerprintSql)).rows[0].md5, testCatalogBefore, "Temporary edit must be fully restored in the test snapshot");
    const health = await fetch(`${url}/health`);
    assert.equal(health.status, 200);
    assert.equal(health.headers.get("x-lauda-environment"), "staging");
    assert.match(health.headers.get("content-security-policy"), /connect-src 'self' https:\/\/testes\.laudaapp\.com/);
    checks.push("Public HTTPS health, environment header and browser connection restriction confirmed");
    const published = await fetch(`${url}/release.json`).then(response => response.json());
    const localRelease = JSON.parse(fs.readFileSync(path.join(root, "mobile/web-build/public-test/release.json"), "utf8").replace(/^\uFEFF/, ""));
    assert.deepEqual(published, localRelease);
    browser = await chromium.launch({ headless: true });
    const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
    const badApiRequests = [];
    page.on("request", request => { if (new URL(request.url()).hostname === "api.laudaapp.com") badApiRequests.push(request.url()); });
    await page.goto(url, { waitUntil: "networkidle" });
    await page.getByTestId("login-email").waitFor();
    const scriptPaths = await page.locator('script[src]').evaluateAll(nodes => nodes.map(node => new URL(node.src).pathname).filter(name => name.endsWith('.js')));
    assert(scriptPaths.length > 0);
    for (const scriptPath of scriptPaths) {
      const served = Buffer.from(await fetch(`${url}${scriptPath}`).then(response => response.arrayBuffer()));
      const local = fs.readFileSync(path.join(root, "mobile/web-build/public-test", scriptPath));
      assert.equal(crypto.createHash("sha256").update(served).digest("hex"), crypto.createHash("sha256").update(local).digest("hex"));
    }
    checks.push("Public release metadata and JavaScript bundles match the validated local build");
    const banner = page.getByTestId("test-environment-banner");
    assert.equal(Math.round((await banner.boundingBox()).height), 22);
    await page.screenshot({ path: path.join(logs, "desktop-login.png"), fullPage: true });
    await page.getByTestId("login-email").fill(email);
    await page.getByTestId("login-password").fill(password);
    await page.getByTestId("login-submit").click();
    await page.waitForURL(current => !current.pathname.includes("login"));
    await page.goto(`${url}/songs/${song.id}`, { waitUntil: "networkidle" });
    await page.getByTestId("current-key").waitFor();
    await page.screenshot({ path: path.join(logs, "desktop-song.png"), fullPage: true });
    await page.setViewportSize({ width: 390, height: 844 });
    await page.reload({ waitUntil: "networkidle" });
    await page.getByTestId("current-key").waitFor();
    await page.screenshot({ path: path.join(logs, "mobile-song.png"), fullPage: true });
    assert.equal(Math.round((await banner.boundingBox()).height), 22);
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > window.innerWidth), false, "Mobile layout must fit the viewport");
    assert.deepEqual(badApiRequests, []);
    checks.push("Browser login, real copied song, desktop/mobile 22px banner; no production API requests");
    const blockedConnection = await page.evaluate(async () => { try { await fetch("https://api.laudaapp.com/health"); return false; } catch { return true; } });
    assert(blockedConnection, "CSP must block production connections from test site");
    checks.push("Browser prevented from connecting to production API by CSP");
    const productionPage = await browser.newPage();
    await productionPage.goto("https://laudaapp.com", { waitUntil: "networkidle" });
    assert.equal(await productionPage.getByTestId("test-environment-banner").count(), 0);
    assert.equal(productionRead(fingerprintSql), productionBefore);
    checks.push("Production site has no test banner; original song catalog remains unchanged");
    fs.writeFileSync(path.join(logs, "verification.json"), JSON.stringify({ verifiedAt: new Date().toISOString(), url, checks, productionCatalogUnchanged: true }, null, 2));
    console.log(JSON.stringify({ url, checks }, null, 2));
  } finally {
    await browser?.close();
    if (song) await pool.query(`UPDATE "Song" SET content=$1,"updatedById"=$2,"updatedAt"=$3 WHERE id=$4`, [song.content, song.updatedById, song.updatedAt, song.id]);
    await pool.query(`DELETE FROM "User" WHERE id=$1`, [userId]);
    await pool.end();
  }
}
main().catch(error => { console.error(error); process.exitCode = 1; });
